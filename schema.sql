CREATE TABLE IF NOT EXISTS papers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    department       VARCHAR(100) NOT NULL,
    exam_type        VARCHAR(30)  NOT NULL CHECK (
        exam_type IN ('Internal Theory', 'Internal Lab', 'Sessional Theory', 'Sessional Lab')
    ),
    subject_code     VARCHAR(50)  NOT NULL,
    subject_name     VARCHAR(150) NOT NULL,
    semester         INT NOT NULL,
    exam_year        INT NOT NULL,
    file_type        VARCHAR(20)  NOT NULL CHECK (
        file_type IN ('direct_upload', 'external_link')
    ),
    file_path_or_url VARCHAR(500) NOT NULL,
    uploaded_by      VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

